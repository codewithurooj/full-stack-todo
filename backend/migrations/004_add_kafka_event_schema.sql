-- ============================================================================
-- 3. ADD IDEMPOTENCY CONSTRAINT TO TASKS TABLE
-- ============================================================================
-- Purpose: Prevent duplicate recurring instances from being created
-- Strategy: Unique constraint on (parent_task_id, due_date) for recurring instances

CREATE UNIQUE INDEX IF NOT EXISTS idx_recurring_instance_dedup
    ON tasks(parent_task_id, due_date)
    WHERE parent_task_id IS NOT NULL;

COMMENT ON INDEX idx_recurring_instance_dedup IS 'Prevents duplicate recurring task instances for same parent and due_date';

-- ============================================================================
-- 4. CREATE NOTIFICATION_SUBSCRIPTIONS TABLE
-- ============================================================================
-- Purpose: Store Web Push notification subscriptions for browser notifications
-- Alternative: Can store in frontend localStorage if simpler for MVP

CREATE TABLE IF NOT EXISTS notification_subscriptions (
    id SERIAL PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL,              -- User who granted notification permission
    endpoint TEXT NOT NULL,                     -- Push service endpoint (e.g., FCM URL)
    p256dh TEXT NOT NULL,                       -- Client public key for message encryption
    auth TEXT NOT NULL,                         -- Authentication secret for encryption
    created_at TIMESTAMPTZ DEFAULT NOW(),       -- Subscription creation timestamp
    updated_at TIMESTAMPTZ DEFAULT NOW(),       -- Last subscription update

    -- Foreign key constraint
    CONSTRAINT fk_notification_subs_user_id
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- Prevent duplicate subscriptions for same user+endpoint
    CONSTRAINT uk_notification_subs_user_endpoint
        UNIQUE(user_id, endpoint)
);

-- Add comment for documentation
COMMENT ON TABLE notification_subscriptions IS 'Web Push notification subscriptions for browser notifications';
COMMENT ON COLUMN notification_subscriptions.endpoint IS 'Push service URL (unique per browser/device)';
COMMENT ON COLUMN notification_subscriptions.p256dh IS 'Public key for encrypting push messages (VAPID)';
COMMENT ON COLUMN notification_subscriptions.auth IS 'Authentication secret for message verification';

-- ============================================================================
-- 5. CREATE INDEX ON NOTIFICATION_SUBSCRIPTIONS
-- ============================================================================
-- Purpose: Fast lookup of subscriptions by user

CREATE INDEX idx_notification_subs_user_id
    ON notification_subscriptions(user_id);

