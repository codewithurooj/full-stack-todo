-- ============================================================================
-- 1. CREATE AUDIT_LOGS TABLE
-- ============================================================================
-- Purpose: Store comprehensive audit trail of all task operations from Kafka events
-- Retention: 90 days (manual cleanup via cron job)

CREATE TABLE IF NOT EXISTS audit_logs (
    id SERIAL PRIMARY KEY,
    event_id UUID UNIQUE NOT NULL,              -- Idempotency key from Kafka event
    timestamp TIMESTAMPTZ NOT NULL,             -- Original event timestamp (not insertion time)
    user_id VARCHAR(255) NOT NULL,              -- User who performed the operation
    task_id INTEGER,                            -- Task affected (NULL for non-task events)
    operation_type VARCHAR(50) NOT NULL,        -- Event type (task.created, task.updated, etc.)
    event_payload JSONB NOT NULL,               -- Full event JSON for forensic analysis
    system_generated BOOLEAN DEFAULT FALSE,     -- TRUE if auto-generated by Recurring Task Service
    created_at TIMESTAMPTZ DEFAULT NOW(),       -- Database insertion timestamp

    -- Foreign key constraints
    CONSTRAINT fk_audit_logs_user_id
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_audit_logs_task_id
        FOREIGN KEY (task_id)
        REFERENCES tasks(id)
        ON DELETE SET NULL,                     -- Keep audit log even if task deleted

    -- Validation constraints
    CONSTRAINT chk_audit_logs_operation_type
        CHECK (operation_type IN ('task.created', 'task.updated', 'task.deleted', 'task.completed')),

    CONSTRAINT chk_audit_logs_timestamp
        CHECK (timestamp <= NOW() + INTERVAL '1 hour')  -- Prevent far-future timestamps
);

-- Add comment for documentation
COMMENT ON TABLE audit_logs IS 'Audit trail of all task operations consumed from Kafka task-events topic';
COMMENT ON COLUMN audit_logs.event_id IS 'UUID from Kafka event (enforces idempotency via UNIQUE constraint)';
COMMENT ON COLUMN audit_logs.timestamp IS 'Original event timestamp from Kafka message';
COMMENT ON COLUMN audit_logs.system_generated IS 'TRUE if event was generated by Recurring Task Service';

-- ============================================================================
-- 2. CREATE INDEXES ON AUDIT_LOGS
-- ============================================================================
-- Purpose: Optimize queries for audit log retrieval and analysis

-- Partial index: Only index rows with non-NULL task_id (saves space)
CREATE INDEX idx_audit_logs_task_id
    ON audit_logs(task_id)
    WHERE task_id IS NOT NULL;

-- Index for querying by user
CREATE INDEX idx_audit_logs_user_id
    ON audit_logs(user_id);

-- Index for querying by timestamp (DESC for recent-first sorting)
CREATE INDEX idx_audit_logs_timestamp
    ON audit_logs(timestamp DESC);

-- Index for filtering by operation type
CREATE INDEX idx_audit_logs_operation_type
    ON audit_logs(operation_type);

